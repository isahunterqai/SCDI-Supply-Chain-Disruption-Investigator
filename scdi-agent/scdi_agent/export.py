"""Export PEE traces to JSON and TypeScript for the SCDI dashboard."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from scdi_agent.loop.pee import IterationTrace


def traces_to_dashboard(traces: list[IterationTrace]) -> list[dict[str, Any]]:
    return [t.to_dashboard() for t in traces]


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


def write_dashboard_ts(path: Path, traces: list[IterationTrace], *, event_name: str) -> None:
    """Overwrite scdi-traces-compatible generated module."""
    rows = traces_to_dashboard(traces)
    body = json.dumps(rows, indent=2)
    # Adapt JSON booleans/null already fine; need TS export wrapper
    content = f"""/* Auto-generated by scdi-agent from historical Kaggle disruption data.
 * Source scenario: {event_name}
 * Do not edit by hand — re-run: python3 -m scdi_agent.cli ingest-and-simulate
 */
export type Verdict = "RETRY" | "CONTINUE" | "PROCEED_TO_FINAL_OUTPUT";

export interface ScdiIteration {{
  iteration: number;
  state: string;
  planner: string;
  executor: {{
    tool: string;
    params: Record<string, string | number>;
  }};
  evaluator: {{
    data_complete: boolean;
    confidence_score: number;
    missing_evidence_detected: boolean;
    verdict: Verdict;
  }};
  metrics: {{
    meterless_tokens_used: number;
    nvidia_nim_latency_ms: number;
    doir_days?: number;
    burn_rate_units_per_day?: number;
    hist_delay_days?: number;
    hist_risk_score?: number;
  }};
  carryover: string;
  hint: string;
}}

/** SCDI run generated from historical disruption scenario: {event_name} */
export const SCDI_ITERATIONS: ScdiIteration[] = {body};
"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
